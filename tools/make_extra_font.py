#!/usr/bin/env python3
"""Regenerate components/todo_display/todo_font_extra.c: the characters the
LVGL built-in Montserrat fonts lack (they stop at ASCII), as a subset of the
same Montserrat Medium TTF, embedded as a C array. The screen renders them at
any size with LVGL's TinyTTF, as a fallback behind the built-in fonts.

    python3 tools/make_extra_font.py   (needs fontTools and the sim build's LVGL)
"""
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "build/sim/_deps/lvgl-src/scripts/built_in_font/Montserrat-Medium.ttf"
OUT = ROOT / "components/todo_display/todo_font_extra.c"

# Beyond ASCII: what people (and Muse) actually write.
RANGES = [
    (0x00A0, 0x00FF),  # Latin-1: é ñ ü ç ß ° © ® × ÷ ¿ ¡ « » ·
    (0x0100, 0x017F),  # Latin Extended-A: ł ő č š ž ...
    (0x2010, 0x2027),  # dashes – —, quotes ‘ ’ “ ”, † • …
    (0x2030, 0x203A),  # ‰ ′ ″ ‹ ›
    (0x20AC, 0x20AC),  # €
    (0x2122, 0x2122),  # ™
    (0x2190, 0x2193),  # ← ↑ → ↓
    (0x2212, 0x2212),  # minus −
]


def main():
    font = TTFont(SRC)
    cmap = font.getBestCmap()
    chars = [u for a, b in RANGES for u in range(a, b + 1) if u in cmap]
    opts = subset.Options()
    opts.layout_features = ["kern"]
    opts.notdef_outline = True
    opts.hinting = False
    opts.name_IDs = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=chars)
    sub.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    data = buf.getvalue()

    lines = [
        "/*",
        " * Generated by tools/make_extra_font.py. Do not edit.",
        " *",
        f" * Montserrat Medium, subset to the {len(chars)} characters beyond ASCII listed in",
        " * that script (accented letters, dashes, curly quotes, ellipsis, ...).",
        " * Copyright 2011 The Montserrat Project Authors; SIL Open Font License 1.1",
        " * (fonts/OFL.txt). Taken from LVGL's scripts/built_in_font.",
        " */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "const uint8_t todo_font_extra_ttf[] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines += ["};", f"const size_t todo_font_extra_ttf_len = {len(data)};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(chars)} characters, {len(data)} bytes")


if __name__ == "__main__":
    main()
